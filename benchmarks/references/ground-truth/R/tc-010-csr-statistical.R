# ─── Helpers ───
round4 <- function(x) {
  if (is.null(x)) return(NULL)
  if (length(x) == 0) return(NULL)
  if (all(is.na(x))) return(NULL)
  round(as.numeric(x), 4)
}

pct <- function(num, den) round4(100 * num / den)

# KM median + 95% CI (log transform, matching Python Greenwood log-transform impl)
km_median_ci <- function(time, event) {
  fit <- survfit(Surv(time, event) ~ 1, conf.type = "log")
  st <- summary(fit)$table
  med <- st["median"]
  ci_lower <- st["0.95LCL"]
  ci_upper <- st["0.95UCL"]
  list(median = round4(med), ci_lower = round4(ci_lower), ci_upper = round4(ci_upper))
}

# Cox PH HR + CI + p (Efron ties, matches lifelines)
cox_result <- function(time, event, trt) {
  df <- data.frame(time = time, event = event, trt = trt)
  fit <- coxph(Surv(time, event) ~ trt, data = df, ties = "efron")
  s <- summary(fit)
  hr <- round4(exp(coef(fit)))
  ci <- round4(exp(confint(fit)))
  p <- round4(s$coefficients[1, "Pr(>|z|)"])
  list(hr = hr, ci_lower = ci[1], ci_upper = ci[2], p = p)
}

# Log-rank p (stratified not needed here; simple 2-arm)
logrank_p <- function(time, event, trt) {
  sd <- survdiff(Surv(time, event) ~ trt)
  p <- round4(1 - pchisq(sd$chisq, df = 1))
  p
}

# Fisher exact p + risk difference + Wald CI
cat_test <- function(a_events, a_n, b_events, b_n) {
  tab <- matrix(c(a_events, a_n - a_events, b_events, b_n - b_events), nrow = 2)
  ft <- fisher.test(tab)
  rd <- round4(a_events / a_n - b_events / b_n)
  # Wald CI for risk difference
  se <- sqrt((a_events / a_n * (1 - a_events / a_n) / a_n) +
             (b_events / b_n * (1 - b_events / b_n) / b_n))
  ci_l <- round4(rd - 1.96 * se)
  ci_u <- round4(rd + 1.96 * se)
  list(rd = rd, ci_lower = ci_l, ci_upper = ci_u, fisher_p = round4(ft$p.value))
}

