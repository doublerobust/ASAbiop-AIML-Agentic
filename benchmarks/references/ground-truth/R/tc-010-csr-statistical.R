    n_ast_3xuln = sum(sub$AST_3XULN == 1), pct_ast_3xuln = pct(sum(sub$AST_3XULN == 1), nrow(sub)),
    n_bili_2xuln = sum(sub$BILI_2XULN == 1), pct_bili_2xuln = pct(sum(sub$BILI_2XULN == 1), nrow(sub)),
    alt_mean = round4(mean(sub$ALT_MAX)), ast_mean = round4(mean(sub$AST_MAX)),
    bili_mean = round4(mean(sub$BILI_MAX))
  )
