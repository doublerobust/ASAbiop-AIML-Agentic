  dispo$by_arm[[arm]] <- list(
    n_randomized = nrow(sub),
    n_completed = sum(sub$DISCONTINUED == 0),
    pct_completed = pct(sum(sub$DISCONTINUED == 0), nrow(sub)),
    n_discontinued = sum(sub$DISCONTINUED == 1),
    pct_discontinued = pct(sum(sub$DISCONTINUED == 1), nrow(sub)),
    n_died = sum(sub$DIED == 1),
    pct_died = pct(sum(sub$DIED == 1), nrow(sub)),
    discontinuation_reasons = as.list(disc_reasons),
    n_major_deviations = sum(sub$MAJOR_DEVIATION == 1),
    pct_major_deviations = pct(sum(sub$MAJOR_DEVIATION == 1), nrow(sub)),
