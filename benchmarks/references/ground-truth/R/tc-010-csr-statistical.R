# ═════════════════════════════════════════════════════════
# Section 11.2: Demographics / Baseline Characteristics
# ═════════════════════════════════════════════════════════
demo <- list(by_arm = list(), overall = list())
demo_vars <- list(
  list(name = "AGE", type = "continuous", label = "Age (years)"),
  list(name = "ECOG", type = "continuous", label = "ECOG PS"),
  list(name = "TRT_DURATION_MO", type = "continuous", label = "Treatment duration (months)")
)
for (arm in arms) {
  sub <- adsl[adsl$TRT01P == arm, ]
  arm_demo <- list(n = nrow(sub))
  for (dv in demo_vars) {
    vals <- sub[[dv$name]]
    arm_demo[[dv$name]] <- list(
      mean = round4(mean(vals)), sd = round4(sd(vals)),
      median = round4(median(vals)), min = round4(min(vals)), max = round4(max(vals))
    )
  }
  # Categorical
  arm_demo$sex <- as.list(table(sub$SEX))
  arm_demo$agegr1 <- as.list(table(sub$AGEGR1))
  arm_demo$race <- as.list(table(sub$RACE))
  arm_demo$ecog_dist <- as.list(table(sub$ECOG))
  arm_demo$disease_stage <- as.list(table(sub$DISEASE_STAGE))
  demo$by_arm[[arm]] <- arm_demo
}
# Overall
sub <- adsl
