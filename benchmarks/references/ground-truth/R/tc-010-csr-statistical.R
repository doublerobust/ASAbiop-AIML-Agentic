  n_subj <- length(unique(sub$USUBJID))
  safety$top_socs_active[[soc_name]] <- list(
    n_subjects = n_subj, pct = pct(n_subj, nrow(adsl[adsl$TRT01P == "Active", ])),
    n_reports = nrow(sub),
    top_pts = as.list(sort(table(sub$AEDECOD), decreasing = TRUE)[1:min(3, length(unique(sub$AEDECOD)))])
  )
