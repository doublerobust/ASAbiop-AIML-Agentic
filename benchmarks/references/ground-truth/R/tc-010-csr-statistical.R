  subj_g3 <- length(unique(sub_ae$USUBJID[sub_ae$AETOXGR >= 3]))
  subj_disc_ae <- length(unique(sub_ae$USUBJID[sub_ae$AEACN == "Drug withdrawn"]))
  subj_died <- sum(sub_adsl$DIED == 1)
  safety$by_arm[[arm]] <- list(
    n = n,
    n_any_ae = subj_with_ae, pct_any_ae = pct(subj_with_ae, n),
    n_sae = subj_sae, pct_sae = pct(subj_sae, n),
    n_grade3_plus = subj_g3, pct_grade3_plus = pct(subj_g3, n),
    n_disc_due_ae = subj_disc_ae, pct_disc_due_ae = pct(subj_disc_ae, n),
    n_deaths = subj_died, pct_deaths = pct(subj_died, n),
    total_ae_reports = nrow(sub_ae),
    n_ae_by_grade = as.list(table(sub_ae$AETOXGR))
  )
}
# Top AEs by SOC (Active arm)
active_ae <- adae[adae$TRT01P == "Active", ]
soc_tab <- sort(table(active_ae$AESOC), decreasing = TRUE)
safety$top_socs_active <- list()
