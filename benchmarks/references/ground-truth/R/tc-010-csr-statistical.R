# --- Primary: PFS ---
pfs <- adtte[adtte$PARAM == "PFS", ]
pfs_result <- list(endpoint = "PFS", method = "Kaplan-Meier + Cox PH + log-rank")
pfs_result$by_arm <- list()
for (arm in arms) {
  sub <- pfs[pfs$TRT01P == arm, ]
  mc <- km_median_ci(sub$AVAL, 1 - sub$CNSR)
  ev <- sum(sub$CNSR == 0)
  pfs_result$by_arm[[arm]] <- list(
    n = nrow(sub), n_events = ev, n_censored = sum(sub$CNSR == 1),
    median = mc$median, ci_lower = mc$ci_lower, ci_upper = mc$ci_upper
  )
}
pfs_result$cox <- cox_result(pfs$AVAL, 1 - pfs$CNSR, pfs$TRT01PN)
pfs_result$logrank_p <- logrank_p(pfs$AVAL, 1 - pfs$CNSR, pfs$TRT01P)
pfs_result$interpretation <- ifelse(pfs_result$cox$p < 0.05,
  "Significant PFS benefit for Active vs Placebo",
  "No significant PFS difference")
result$section_11_4_efficacy$primary_pfs <- pfs_result

# --- Secondary: OS ---
os <- adtte[adtte$PARAM == "OS", ]
os_result <- list(endpoint = "OS", method = "Kaplan-Meier + Cox PH + log-rank")
os_result$by_arm <- list()
for (arm in arms) {
  sub <- os[os$TRT01P == arm, ]
  mc <- km_median_ci(sub$AVAL, 1 - sub$CNSR)
  os_result$by_arm[[arm]] <- list(
    n = nrow(sub), n_events = sum(sub$CNSR == 0), n_censored = sum(sub$CNSR == 1),
    median = mc$median, ci_lower = mc$ci_lower, ci_upper = mc$ci_upper
  )
}
os_result$cox <- cox_result(os$AVAL, 1 - os$CNSR, os$TRT01PN)
os_result$logrank_p <- logrank_p(os$AVAL, 1 - os$CNSR, os$TRT01P)
result$section_11_4_efficacy$secondary_os <- os_result

# --- Secondary: ORR and DCR ---
orr_result <- list(endpoint = "ORR (CR+PR)", method = "RECIST 1.1")
orr_result$by_arm <- list()
for (arm in arms) {
  sub <- adrs[adrs$TRT01P == arm, ]
  n <- nrow(sub)
  n_responders <- sum(sub$AVALC %in% c("CR", "PR"))
  n_dcr <- sum(sub$AVALC %in% c("CR", "PR", "SD"))
  orr_result$by_arm[[arm]] <- list(
    n = n, n_responders = n_responders, orr_pct = pct(n_responders, n),
    n_dcr = n_dcr, dcr_pct = pct(n_dcr, n),
    bor_dist = as.list(table(sub$AVALC))
  )
}
# ORR risk difference + Fisher
a_sub <- adrs[adrs$TRT01P == "Active", ]
p_sub <- adrs[adrs$TRT01P == "Placebo", ]
a_resp <- sum(a_sub$AVALC %in% c("CR", "PR"))
p_resp <- sum(p_sub$AVALC %in% c("CR", "PR"))
orr_result$risk_difference <- cat_test(a_resp, nrow(a_sub), p_resp, nrow(p_sub))
a_dcr <- sum(a_sub$AVALC %in% c("CR", "PR", "SD"))
p_dcr <- sum(p_sub$AVALC %in% c("CR", "PR", "SD"))
orr_result$dcr_risk_difference <- cat_test(a_dcr, nrow(a_sub), p_dcr, nrow(p_sub))
result$section_11_4_efficacy$secondary_orr_dcr <- orr_result

# --- Subgroup analysis (forest plot HRs) ---
subgroups <- list(
  list(var = "SEX", label = "Sex (M vs F)"),
  list(var = "AGEGR1", label = "Age group (<65 vs >=65)"),
  list(var = "ECOG", label = "ECOG (0 vs 1)"),
  list(var = "DISEASE_STAGE", label = "Disease stage (IIIB vs IV)")
)
subgroup_results <- list()
pfs_adsl <- merge(pfs, adsl[, c("USUBJID", "SEX", "AGEGR1", "ECOG", "DISEASE_STAGE")],
                  by = "USUBJID", all.x = TRUE)
for (sg in subgroups) {
  sg_res <- list()
  levels <- sort(unique(pfs_adsl[[sg$var]]))
  for (lv in levels) {
    sub <- pfs_adsl[pfs_adsl[[sg$var]] == lv, ]
    if (nrow(sub) > 5 && length(unique(sub$TRT01PN)) == 2 && sum(sub$CNSR == 0) > 2) {
      cox <- tryCatch(cox_result(sub$AVAL, 1 - sub$CNSR, sub$TRT01PN),
                      error = function(e) NULL)
      sg_res[[as.character(lv)]] <- list(
        n = nrow(sub), n_events = sum(sub$CNSR == 0),
        hr = cox$hr, ci_lower = cox$ci_lower, ci_upper = cox$ci_upper, p = cox$p
      )
    } else {
      sg_res[[as.character(lv)]] <- list(n = nrow(sub), n_events = sum(sub$CNSR == 0), hr = NULL)
    }
  }
  subgroup_results[[sg$var]] <- sg_res
}
result$section_11_4_efficacy$subgroup_forest <- subgroup_results

# --- Sensitivity analysis: PFS censoring at subsequent therapy ---
# Approximate: subjects who discontinued due to "Disease progression" or died
# have events; others censored at last follow-up. Here we re-analyze PFS
# censoring subjects who started new anticancer therapy (proxy: discontinued
# for reasons other than progression/death → censor at discontinuation).
pfs_sens <- pfs
adsl_disc <- adsl[, c("USUBJID", "DISC_REASON", "FOLLOWUP_DAYS")]
pfs_sens <- merge(pfs_sens, adsl_disc, by = "USUBJID", all.x = TRUE)
# If discontinued for reasons other than disease progression and had an event,
# treat as censored at followup_days (sensitivity to informative censoring)
pfs_sens$CNSR_sens <- pfs_sens$CNSR
pfs_sens$AVAL_sens <- pfs_sens$AVAL
mask <- pfs_sens$DISC_REASON %in% c("Withdrawal by subject", "Physician decision") &
         pfs_sens$CNSR == 0
pfs_sens$CNSR_sens[mask] <- 1
pfs_sens$AVAL_sens[mask] <- pmin(pfs_sens$AVAL_sens[mask], pfs_sens$FOLLOWUP_DAYS[mask])

sens_result <- list(method = "Censor at last follow-up if discontinued for non-progression reasons")
sens_result$cox <- cox_result(pfs_sens$AVAL_sens, 1 - pfs_sens$CNSR_sens, pfs_sens$TRT01PN)
sens_result$logrank_p <- logrank_p(pfs_sens$AVAL_sens, 1 - pfs_sens$CNSR_sens, pfs_sens$TRT01P)
result$section_11_4_efficacy$sensitivity_pfs <- sens_result

